import {chromium} from '@playwright/test';
import {boardSchema} from '../src/lib/board.ts';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
const page=await browser.newPage({viewport:{width:1200,height:900},deviceScaleFactor:1});
await page.goto(process.env.TEST_BASE_URL||'http://127.0.0.1:5174/');
await page.getByRole('textbox',{name:'榜单标题'}).waitFor();
const s = boardSchema.parse(await page.evaluate((): unknown => JSON.parse(localStorage.getItem('tier-studio-v1') ?? 'null')));
await page.evaluate(s=>{
 s.title='2026 AI 大模型排位';
 const pool=[...s.pool];[[0,1],[2,3,4],[5,6,8],[9,7],[10,11],[12,13]].forEach((ix,i)=>{const row=s.rows[i];if(row) row.items=ix.flatMap(j=>{const item=pool[j];return item?[item]:[];});});s.pool=[];
 localStorage.setItem('tier-studio-v1',JSON.stringify(s));
}, s);
await page.reload();await page.getByRole('textbox',{name:'榜单标题'}).waitFor();
await page.evaluate(()=>{const canvas=document.querySelector<HTMLElement>('.export-canvas');if(!canvas) throw Error('Missing export canvas');document.body.replaceChildren(canvas);Object.assign(document.body.style,{padding:'48px',height:'900px',background:'#0c0d10',display:'flex',alignItems:'center'});Object.assign(canvas.style,{width:'1104px',flexShrink:0});document.querySelectorAll('.no-export').forEach(e=>e.remove());});
await page.screenshot({path:'./poster.png'});
const icon=await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=256;canvas.height=256;const ctx=canvas.getContext('2d');if(!ctx) throw Error('Canvas unavailable');ctx.fillStyle='#0c0d10';ctx.fillRect(0,0,256,256);['#fb7299','#c95a7a','#8f4057'].forEach((color,i)=>{ctx.fillStyle=color;ctx.beginPath();ctx.roundRect(55+i*52,58+i*38,36,140-i*38,5);ctx.fill();});return canvas.toDataURL('image/png').split(',')[1];});
await writeFile('icon.png',Buffer.from(icon ?? '', 'base64'));
await mkdir('artifacts',{recursive:true});
await browser.close();
console.log('Created poster.png (1200×900) and icon.png (256×256).');
